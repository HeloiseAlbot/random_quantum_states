from typing import Callable
import numpy as np 

def produce_samples(function_to_sample: Callable, args_dict: dict, n_samples: int=10000)-> np.array:
    """
    Produce n_samples of the function function_to_sample the Kullback–Leibler divergence between two distributions generated by func1 and func2.
    
    Parameters:
        function_to_sample (callable): A function generating a random number.
        args_dict (dict): A dictionary of arguments to pass to function_to_sample.
        n_samples (int): Number of samples to draw from each function.
        
    Returns:
        samples (np.array): The samples of the function function_to_sample.
    """    
    # Generates n_samples random state vectors of dimension n.
    samples = np.array([function_to_sample(**args_dict) for _ in range(n_samples)])
    return samples

def compute_kl_divergence_from_fcts(func1: Callable, func2: Callable, args_dict_1: dict, args_dict_2: dict, n_samples: int=10000, bins: int=50, range_proba: tuple=None)->(float, np.array, np.array):
    """
    Computes the Kullback–Leibler divergence between two distributions generated by func1 and func2.
    
    Parameters:
        func1 (callable): A function generating a random number from distribution P.
        func2 (callable): A function generating a random number from distribution Q.
        args_dict_1 (dict): A dictionary of arguments to pass to func1.
        args_dict_2 (dict): A dictionary of arguments to pass to func2.
        n_samples (int): Number of samples to draw from each function.
        bins (int): Number of bins to use for the histogram.
        range (tuple): The range of the histograms (min, max).
        
    Returns:
        kl_div (float): The KL divergence D_KL(P || Q).
        samples1 (np.array): The samples from the function P.
        samples2 (np.array): The sampels fron the function Q.
    """    
    # Generates n_samples random state vectors of dimension n.
    samples1 = np.array([func1(**args_dict_1) for _ in range(n_samples)])
    samples2 = np.array([func2(**args_dict_2) for _ in range(n_samples)])
    
    # Create histograms
    hist1, bin_edges = np.histogram(samples1, bins=bins, range=range_proba, density=True)
    hist2, _ = np.histogram(samples2, bins=bin_edges, density=True)
    
    # Avoid divide-by-zero and log(0) by replacing zero probabilities with a small value
    hist1 = np.clip(hist1, 1e-10, None)
    hist2 = np.clip(hist2, 1e-10, None)
    
    # Compute KL divergence
    kl_div = np.sum(hist1 * np.log(hist1 / hist2))
    
    return kl_div, samples1, samples2

def compute_kl_divergence_from_samples(samples1: np.array, samples2: np.array, bins: int=50, range_proba: tuple=None)-> float:
    """
    Computes the Kullback–Leibler divergence between two distributions which as produce samples1
    and samples2.
    
    Parameters:
        samples1 (callable): The sample of random numbers generated by the distribution P.
        samples2 (callable): The sample of random numbers generated by the distribution Q
        bins (int): Number of bins to use for the histogram.
        range (tuple): The range of the histograms (min, max).
        
    Returns:
        kl_div (float): The KL divergence D_KL(P || Q).
    """  
    if len(samples1) != len(samples2):
        # They should contain the same number of samples: n_samples 
        raise ValueError(
        f"Mismatch in number of samples: samples1 has {len(samples1)} elements, "
        f"while samples2 has {len(samples2)}. They should have the same number of samples.")
        
    # Create histograms
    hist1, bin_edges = np.histogram(samples1, bins=bins, range=range_proba, density=True)
    hist2, _ = np.histogram(samples2, bins=bin_edges, density=True)
    
    # Avoid divide-by-zero and log(0) by replacing zero probabilities with a small value
    hist1 = np.clip(hist1, 1e-10, None)
    hist2 = np.clip(hist2, 1e-10, None)
    
    # Compute KL divergence
    kl_div = np.sum(hist1 * np.log(hist1 / hist2))
    
    return kl_div


